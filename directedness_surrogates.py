"""
Is the in-vivo directedness generated by the recorded units or inherited from stimuli,
rhythms and rates?  (referee control on the lag-1 directedness index)

The index of directedness.py measures the antisymmetric fraction of the excess lag-1
cross-correlation power over circular-shift surrogates (shifts >= 1 s).  Such surrogates
destroy stimulus locking and rhythm-phase relations, so antisymmetry produced by onset
latencies across areas, or by different theta phases of the units, is counted as
directedness.  Here the index is recomputed against surrogates that preserve them:
  Allen (10 cached sessions, 256 most active units, 10 ms; spontaneous and five stimuli)
    presentation-locked surrogate: the activity is aligned to the presentations (250 ms
      flashes, 2 s gratings, 120 s movie repeats) and every unit's presentations are
      rotated by a random offset, which keeps its stimulus-locked response (PSTH) and
      destroys only the unit-to-unit timing; also the standard index on the activity
      with the PSTH of every unit subtracted
    rate matching: spikes thinned so that every unit has the same rate in the stimulus
      and in spontaneous activity (the smaller of the two), then the standard index
  CA1 (DANDI 000044, 8 sessions, streamed; Maze, REM and NREM at 10 and 20 ms)
    jitter surrogate: every spike displaced by a uniform random offset within +/- 25 ms
      or +/- 100 ms, which destroys the fine timing but keeps the slow co-modulation
      (100 ms: also the theta-phase relations)
Results: results/directedness_surrogates.npz (Allen), results/directedness_surrogates_ca1.npz (CA1); table on stdout (summary).
Run from the folder holding data/ and results/:
    python directedness_surrogates.py allen | ca1 | summary
"""

import glob
import os
import sys
import time
import numpy as np

from directedness import _parts
from rg_metrics import shift_surrogate
from invivo_binsize import bin_condition, CACHE, N_UNITS
from allen_rest_vs_task import condition_bins

OUT = "results/directedness_surrogates.npz"      # Allen; the CA1 part writes to results/directedness_surrogates_ca1.npz
OUT_CA1 = "results/directedness_surrogates_ca1.npz"
DT = 0.010
PERIOD_S = {"natural_scenes": 0.25, "static_gratings": 0.25, "gabors": 0.25, "drifting_gratings": 3.0, "natural_movie_three": 120.0}
JITTERS = (0.025, 0.100)


def directedness_surr(S, surr, n_surr=3, seed=0):
    """Directedness with a custom surrogate generator surr(S, rng) -> surrogate activity."""
    S = np.asarray(S, np.float32)
    S = S[:, S.std(0) > 0]
    a, y = _parts(S, (1,))
    rng = np.random.default_rng(seed)
    sa, sy = np.mean([_parts(surr(S, rng), (1,)) for _ in range(n_surr)], 0)
    A, Y = a - sa, y - sy
    return float(A / (A + Y)) if A + Y > 0 else np.nan


def standard(S, rng):
    return shift_surrogate(S, rng)


def block_shift(P):
    def surr(S, rng):
        T, N = S.shape
        nb = T // P
        if nb < 3:
            return shift_surrogate(S, rng)
        out = np.empty_like(S)
        for i in range(N):
            out[:, i] = np.roll(S[:, i], int(rng.integers(1, nb)) * P)
        return out
    return surr


def thin_to_rate(B, target, rng):
    """Delete spikes at random so that the rate of every unit does not exceed target (per unit)."""
    B = B.copy()
    r = B.mean(0)
    for j in np.flatnonzero(r > target):
        idx = np.flatnonzero(B[:, j])
        drop = rng.choice(idx, int(round(len(idx) * (1 - target[j] / r[j]))), replace=False)
        B[drop, j] = 0
    return B


# ----------------------------------------------------------------------------- Allen
SEG = {"natural_scenes": (1, 0.25), "static_gratings": (1, 0.21), "gabors": (1, 0.23), "drifting_gratings": (1, 1.98),
       "natural_movie_three": (3600, 120.0)}          # (presentations per segment, segment duration in s)


def aligned(spikes, onsets, nb, dt):
    """(segments x nb bins x units) binary tensor, bins counted from the onset of every segment."""
    A = np.zeros((len(onsets), nb, len(spikes)), np.uint8)
    for j, s in enumerate(spikes):
        for i, t0 in enumerate(onsets):
            k = ((s[(s >= t0) & (s < t0 + nb * dt)] - t0) / dt).astype(int)
            A[i, k[k < nb], j] = 1
    return A


def roll_segments(A, rng):
    """Surrogate that keeps the stimulus-locked response of every unit: its segments are rotated by a random offset."""
    out = np.empty_like(A)
    for j in range(A.shape[2]):
        out[:, :, j] = np.roll(A[:, :, j], int(rng.integers(1, A.shape[0])), axis=0)
    return out


def run_allen():
    store = dict(np.load(OUT)) if os.path.exists(OUT) else {}
    for f in sorted(glob.glob(f"{CACHE}/*.npz")):
        ses = os.path.basename(f).replace(".npz", "")
        d = np.load(f)
        spikes = np.split(d["spikes"], d["index"][:-1])
        top = np.sort(np.argsort(-d["fr"])[:N_UNITS])
        spikes = [spikes[i] for i in top]
        T_eq = int(float(d["T_eq_min"]) * 60 / DT)
        inv = d["inv"]
        t0 = time.time()
        for c, (per_seg, dur) in SEG.items():
            key = f"allen/{ses}/{c}"
            if f"iv/{c}" not in d or f"{key}/std" in store:
                continue
            nb = int(dur / DT)
            iv = d[f"iv/{c}"]
            onsets = iv[::per_seg, 0]
            onsets = onsets[[not np.any((inv[:, 0] < t + nb * DT) & (inv[:, 1] > t)) for t in onsets]] if len(inv) else onsets
            onsets = onsets[:max(3, T_eq // nb)]
            A = aligned(spikes, onsets, nb, DT)
            # spontaneous activity cut into segments of the same length
            sp = d["iv/spontaneous"]
            on_sp = np.concatenate([np.arange(s, e - nb * DT, nb * DT) for s, e in sp if e - s > nb * DT])[:len(onsets)]
            A0 = aligned(spikes, on_sp, nb, DT)
            rng = np.random.default_rng(1)
            res = {}
            for lab, X in [("", A), ("spont_", A0)]:
                flat = X.reshape(-1, X.shape[2]).astype(np.float32)
                res[lab + "std"] = directedness_surr(flat, standard)
                res[lab + "pres"] = directedness_surr(flat, lambda S, r, X=X: roll_segments(X, r).reshape(-1, X.shape[2]).astype(np.float32))
                psth = X.mean(0, keepdims=True)
                res[lab + "psth"] = directedness_surr((X - psth).reshape(-1, X.shape[2]), standard)
            target = np.minimum(A.reshape(-1, A.shape[2]).mean(0), A0.reshape(-1, A0.shape[2]).mean(0))
            res["ratematched"] = directedness_surr(thin_to_rate(A.reshape(-1, A.shape[2]), target, rng), standard)
            res["spont_ratematched"] = directedness_surr(thin_to_rate(A0.reshape(-1, A0.shape[2]), target, rng), standard)
            for k, v in res.items():
                store[f"{key}/{k}"] = v
            store[f"{key}/segments"] = len(onsets)
            print(f"  {ses} {c:20s} ({len(onsets):4d} segments of {nb} bins): std {res['std']:.3f}/{res['spont_std']:.3f}  "
                  f"locked surrogate {res['pres']:.3f}/{res['spont_pres']:.3f}  psth-subtracted {res['psth']:.3f}/{res['spont_psth']:.3f}  "
                  f"rate-matched {res['ratematched']:.3f}/{res['spont_ratematched']:.3f}   (stimulus/spontaneous)", flush=True)
        np.savez(OUT, **store)
        print(f"{ses} done [{time.time() - t0:.0f} s]", flush=True)


# ----------------------------------------------------------------------------- CA1
def ca1_urls(dandiset="000044"):
    from dandi.dandiapi import DandiAPIClient
    with DandiAPIClient() as c:
        for a in c.get_dandiset(dandiset).get_assets():
            if a.path.endswith(".nwb"):
                yield a.path, a.get_content_url(follow_redirects=1, strip_query=True)


def jitter(spikes, w, rng):
    return [s + rng.uniform(-w, w, len(s)) for s in spikes]


def run_ca1():
    from hc11_sequences import load, binned
    store = dict(np.load(OUT_CA1)) if os.path.exists(OUT_CA1) else {}
    for path, url in ca1_urls():
        ses = os.path.basename(path).replace(".nwb", "")
        if any(k.startswith(f"ca1/{ses}/") for k in store):
            continue
        t0 = time.time()
        spikes, epochs, states = load(url)
        segs = {"Maze": [epochs[k] for k in epochs if "maze" in k.lower()]}
        if states is not None:
            for lab in ("REM", "NREM"):
                m = states["label"] == lab
                segs[lab] = [(a, b) for a, b in zip(states["start"][m], states["stop"][m]) if b - a > 0]
        rng = np.random.default_rng(2)
        for name, sg in segs.items():
            if not sg or sum(b - a for a, b in sg) < 60:
                continue
            for dt in (0.010, 0.020):
                B = np.concatenate([binned(spikes, a, b, dt) for a, b in sg])
                rate = B.mean(0) / dt
                ok = np.flatnonzero(rate > 0.5)
                nmax = min(len(ok), len(B) // 100)
                if nmax < 16:
                    continue
                sel = np.sort(ok[np.argsort(-rate[ok])][:nmax])
                key = f"ca1/{ses}/{name}/{int(dt * 1000)}"
                S = B[:, sel]
                store[f"{key}/std"] = directedness_surr(S, standard)
                store[f"{key}/n"] = len(sel)
                for w in JITTERS:
                    def surr(S_, rng_, w=w, sg=sg, dt=dt, sel=sel):
                        Bj = np.concatenate([binned(jitter([spikes[i] for i in sel], w, rng_), a, b, dt) for a, b in sg])
                        return Bj.astype(np.float32)
                    store[f"{key}/jit{int(w * 1000)}"] = directedness_surr(S, surr)
                print(f"  {ses} {name:5s} {int(dt * 1000):2d} ms: {len(sel):3d} units, std {store[f'{key}/std']:.3f}  "
                      f"vs jitter 25 ms {store[f'{key}/jit25']:.3f}  100 ms {store[f'{key}/jit100']:.3f}", flush=True)
        np.savez(OUT_CA1, **store)
        print(f"{ses} done [{time.time() - t0:.0f} s]", flush=True)


def summary():
    from scipy.stats import wilcoxon
    store = {}
    for f in (OUT, OUT_CA1):
        if os.path.exists(f):
            store.update(dict(np.load(f)))
    ses = sorted({k.split("/")[1] for k in store if k.startswith("allen/")})
    if ses:
        print(f"=== Allen, {len(ses)} sessions: directedness, stimulus minus spontaneous (mean; sessions > 0; Wilcoxon) [stimulus level]")
        for c in SEG:
            rows = []
            for s in ses:
                k = f"allen/{s}/{c}"
                if f"{k}/std" in store:
                    rows.append([store[f"{k}/{q}"] - store[f"{k}/spont_{q}"] for q in ("std", "pres", "psth", "ratematched")] +
                                [store[f"{k}/{q}"] for q in ("std", "pres", "psth", "ratematched")])
            if len(rows) < 3:
                continue
            r = np.array(rows)
            def fmt(v):
                v = v[~np.isnan(v)]
                return f"{v.mean():+.3f} ({np.sum(v > 0)}/{len(v)}, p={wilcoxon(v).pvalue if len(v) >= 5 else np.nan:.2g})"
            print(f"  {c:20s} n={len(r):2d}: standard {fmt(r[:, 0])} | locked surrogate {fmt(r[:, 1])} | psth-subtracted {fmt(r[:, 2])} | rate-matched {fmt(r[:, 3])}"
                  f"  [{np.nanmean(r[:, 4]):.3f} {np.nanmean(r[:, 5]):.3f} {np.nanmean(r[:, 6]):.3f} {np.nanmean(r[:, 7]):.3f}]")
    ses = sorted({k.split("/")[1] for k in store if k.startswith("ca1/")})
    if ses:
        print(f"\n=== CA1, {len(ses)} sessions: directedness against shift (standard) and jitter surrogates")
        for name in ("Maze", "REM", "NREM"):
            for dt in (10, 20):
                rows = np.array([[store[f"ca1/{s}/{name}/{dt}/std"], store[f"ca1/{s}/{name}/{dt}/jit25"], store[f"ca1/{s}/{name}/{dt}/jit100"]]
                                 for s in ses if f"ca1/{s}/{name}/{dt}/std" in store])
                if len(rows):
                    print(f"  {name:5s} {dt:2d} ms n={len(rows)}: standard {np.nanmean(rows[:, 0]):.3f}  excess over 25-ms jitter {np.nanmean(rows[:, 1]):.3f}  over 100-ms jitter {np.nanmean(rows[:, 2]):.3f}")


if __name__ == "__main__":
    os.makedirs("results", exist_ok=True)
    what = sys.argv[1] if len(sys.argv) > 1 else "summary"
    if what == "allen":
        run_allen()
    elif what == "ca1":
        run_ca1()
    summary()
